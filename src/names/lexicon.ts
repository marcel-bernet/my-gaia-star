/** Spanish 1–32; numbers ending in "one" agree with the noun (veintiún zorros, veintiuna grullas). */
export function countEs(n: number, g: Gender): string {
  const ones = ['', 'un', 'dos', 'tres', 'cuatro', 'cinco', 'seis', 'siete', 'ocho', 'nueve'];
  const teens = ['diez', 'once', 'doce', 'trece', 'catorce', 'quince', 'dieciséis', 'diecisiete', 'dieciocho', 'diecinueve'];
  const twenties = [
    'veinte',
    'veintiún',
    'veintidós',
    'veintitrés',
    'veinticuatro',
    'veinticinco',
    'veintiséis',
    'veintisiete',
    'veintiocho',
    'veintinueve',
  ];
  const fem = (s: string) => (g === 'f' ? s.replace(/ún$/, 'una').replace(/^un$/, 'una').replace(/ un$/, ' una') : s);
  if (n < 10) return fem(ones[n]);
  if (n < 20) return teens[n - 10];
  if (n < 30) return fem(twenties[n - 20]);
  return fem(n === 30 ? 'treinta' : `treinta y ${ones[n - 30]}`);
}

/** Catalan 1–32; one and two agree with the noun (un/una, dos/dues). */
export function countCa(n: number, g: Gender): string {
  const ones = ['', 'un', 'dos', 'tres', 'quatre', 'cinc', 'sis', 'set', 'vuit', 'nou'];
  const teens = ['deu', 'onze', 'dotze', 'tretze', 'catorze', 'quinze', 'setze', 'disset', 'divuit', 'dinou'];
  const unit = (k: number) => (g === 'f' && k === 1 ? 'una' : g === 'f' && k === 2 ? 'dues' : ones[k]);
  if (n < 10) return unit(n);
  if (n < 20) return teens[n - 10];
  if (n < 30) return n === 20 ? 'vint' : `vint-i-${unit(n - 20)}`;
  return n === 30 ? 'trenta' : `trenta-${unit(n - 30)}`;
}
